export const DEFAULT_DESTINATION = "danang";

/**
 * Get the first verified image for a destination.
 * Falls back to danang if destination not found.
 */
export function getDestinationImage(destination: string): string {
  const key = normalizeDestinationKey(destination);
  return DESTINATION_IMAGES[key]?.[0] ?? DESTINATION_IMAGES[DEFAULT_DESTINATION][0];
}

/**
 * Get all verified images for a destination.
 * Falls back to danang if destination not found.
 */
export function getDestinationImages(destination: string): string[] {
  const key = normalizeDestinationKey(destination);
  return DESTINATION_IMAGES[key] ?? DESTINATION_IMAGES[DEFAULT_DESTINATION];
}

/**
 * Normalize a destination name into a lookup key.
 * e.g. "Hội An" → "hoian", "Đà Nẵng" → "danang", "TP. HCM" → "hochiminh"
 */
export function normalizeDestinationKey(destination: string): string {
  const d = destination.toLowerCase().trim();

  // Exact & fuzzy matches
  const map: Record<string, string> = {
    "đà nẵng": "danang", "da nang": "danang", "danang": "danang",
    "hội an": "hoian", "hoi an": "hoian", "hoian": "hoian",
    "phú quốc": "phuquoc", "phu quoc": "phuquoc", "phuquoc": "phuquoc",
    "nha trang": "nhatrang", "nha-trang": "nhatrang", "nhatrang": "nhatrang",
    "hạ long": "halong", "ha long": "halong", "halong": "halong",
    "sapa": "sapa", "sa pa": "sapa",
    "đà lạt": "dalat", "da lat": "dalat", "dalat": "dalat",
    "bangkok": "bangkok",
    "hà nội": "hanoi", "ha noi": "hanoi", "hanoi": "hanoi",
    "huế": "hue", "hue": "hue",
    "côn đảo": "condao", "con dao": "condao", "condao": "condao",
    "miền tây": "mientay", "mien tay": "mientay", "mientay": "mientay",
    "seoul": "seoul",
    "tokyo": "tokyo",
    "bali": "bali",
    "singapore": "singapore",
  };

  // Try exact match first
  if (map[d]) return map[d];

  // Try partial match
  for (const [key, val] of Object.entries(map)) {
    if (d.includes(key) || key.includes(d)) return val;
  }

  // Unknown — return default
  return DEFAULT_DESTINATION;
}
